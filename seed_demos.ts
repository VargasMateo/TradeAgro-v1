async function seed() {
  try {
    const connection = await pool.getConnection();
    console.log('Connected to database. Ensuring table exists...');
    
    await connection.query(`
      CREATE TABLE IF NOT EXISTS demo_padron (
        id INT AUTO_INCREMENT PRIMARY KEY,
        cuit VARCHAR(20) NOT NULL UNIQUE,
        razonSocial VARCHAR(255) NOT NULL,
        isActive BOOLEAN DEFAULT TRUE,
        expiresAt DATETIME DEFAULT NULL,
        createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
      ) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
    `);

    // Ensure demo user has password set just in case
    const demoEmail = process.env.DEMO_EMAIL || 'demo@tradeagro.com';
    const [demoCheck]: any = await connection.query('SELECT id, password FROM users WHERE email = ?', [demoEmail]);
    if (demoCheck.length > 0 && demoCheck[0].password === '__PASSWORD_NOT_SET__') {
      console.log('Setting password for demo account...');
      const bcrypt = require('bcrypt');
      const demoPass = await bcrypt.hash('tradeagro2026!', 10);
      await connection.query('UPDATE users SET password = ? WHERE id = ?', [demoPass, demoCheck[0].id]);
    }

    console.log(`Seeding ${clients.length} demo accounts...`);
    let inserted = 0;
    
    for (const client of clients) {
      try {
        await connection.query(
          'INSERT INTO demo_padron (cuit, razonSocial, isActive) VALUES (?, ?, ?)',
          [client.cuit.trim(), client.razonSocial.trim(), true]
        );
        inserted++;
      } catch (err: any) {
        if (err.code === 'ER_DUP_ENTRY') {
          // Ya existe
        } else {
          console.error(`Failed to insert ${client.cuit}: ${err.message}`);
        }
      }
    }
    
    console.log(`Successfully inserted ${inserted} new accounts.`);
    connection.release();
    process.exit(0);
  } catch (error) {
    console.error('Migration failed:', error);
    process.exit(1);
  }
}

